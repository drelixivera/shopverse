// Get current user from token (supports both mock and Google tokens)
export const getCurrentUser = async (token) => {
  // Simulate network delay
  await new Promise(resolve => setTimeout(resolve, 300));

  if (!token) {
    throw new Error('No token provided');
  }

  // ===== Try Google Token =====
  try {
    const decoded = jwtDecode(token);
    // Check if it's a Google token (has 'sub' field)
    if (decoded.sub && decoded.email) {
      // Check if this Google user exists in our mock database
      // If not, create a new user entry
      let existingUser = users.find(u => u.email.toLowerCase() === decoded.email.toLowerCase());
      
      if (!existingUser) {
        // Create a new user for this Google account
        const newUser = {
          id: `google_${decoded.sub}`,
          name: decoded.name || decoded.given_name || 'Google User',
          email: decoded.email,
          picture: decoded.picture || null,
          provider: 'google',
          createdAt: new Date().toISOString()
        };
        users.push(newUser);
        saveUsers();
        existingUser = newUser;
      }
      
      // Return user data
      const { password: _, ...userWithoutPassword } = existingUser;
      return {
        ...userWithoutPassword,
        picture: decoded.picture || userWithoutPassword.picture || null,
      };
    }
  } catch {
    // Not a Google token, continue to mock token check
  }

  // ===== Try Mock Token =====
  const payload = verifyToken(token);
  if (!payload) {
    throw new Error('Invalid or expired token');
  }

  const user = users.find(u => u.id === payload.id);
  if (!user) {
    throw new Error('User not found');
  }

  const { password: _, ...userWithoutPassword } = user;
  return userWithoutPassword;
};

