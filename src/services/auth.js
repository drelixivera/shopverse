// ✅ Verify Google token
// Google tokens are already verified by the @react-oauth/google library
// This function is for additional validation if needed
export const verifyGoogleToken = async (token) => {
  try {
    // Decode the token to check if it's valid
    const decoded = jwtDecode(token);
    
    // Check if it has required Google fields
    if (!decoded.sub || !decoded.email) {
      throw new Error('Invalid Google token: missing required fields');
    }
    
    // Optional: Verify with Google's tokeninfo endpoint
    // const response = await fetch(`https://oauth2.googleapis.com/tokeninfo?id_token=${token}`);
    // const data = await response.json();
    // if (!data.email) throw new Error('Invalid token');
    
    return { success: true, userData: decoded };
  } catch (error) {
    console.error('Google token verification failed:', error);
    throw new Error('Invalid Google token');
  }
};

