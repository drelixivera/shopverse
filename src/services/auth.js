// ============================================
// 1. MOCK USER DATABASE
// ============================================
// Users are stored in localStorage for persistence
// In a real app, this would be a database on a server

let users = [];

// Load users from localStorage
const loadUsers = () => {
  try {
    const saved = localStorage.getItem('auth_users');
    if (saved) {
      users = JSON.parse(saved);
    } else {
      // Seed with a test user if no users exist
      users = [
        {
          id: '1',
          name: 'Test User',
          email: 'test@example.com',
          password: 'password123',
          createdAt: new Date().toISOString()
        }
      ];
      localStorage.setItem('auth_users', JSON.stringify(users));
    }
  } catch (error) {
    console.error('Error loading users:', error);
    users = [];
  }
};

// Save users to localStorage
const saveUsers = () => {
  try {
    localStorage.setItem('auth_users', JSON.stringify(users));
  } catch (error) {
    console.error('Error saving users:', error);
  }
};

// Load users on initialization
loadUsers();

// ============================================
// 2. JWT TOKEN HELPERS
// ============================================
// Generate a fake JWT token for our mock auth
// In a real app, this would be generated by the server

const generateToken = (user) => {
  const payload = {
    id: user.id,
    email: user.email,
    name: user.name,
    exp: Date.now() + 7 * 24 * 60 * 60 * 1000 // 7 days expiry
  };
  return btoa(JSON.stringify(payload));
};

// Verify a mock JWT token
export const verifyToken = (token) => {
  try {
    const payload = JSON.parse(atob(token));
    if (payload.exp < Date.now()) {
      return null;
    }
    return payload;
  } catch (error) {
    return null;
  }
};

// ============================================
// 3. EMAIL/PASSWORD AUTH
// ============================================

// Login with email and password
export const loginUser = async (email, password) => {
  // Simulate network delay
  await new Promise(resolve => setTimeout(resolve, 800));

  // Validate inputs
  if (!email || !password) {
    throw new Error('Email and password are required');
  }

  // Find user by email
  const user = users.find(u => u.email.toLowerCase() === email.toLowerCase());
  
  if (!user) {
    throw new Error('Invalid email or password');
  }

  // Check password (in real app, this would use bcrypt compare)
  if (user.password !== password) {
    throw new Error('Invalid email or password');
  }

  // Generate token and return user data (excluding password)
  const token = generateToken(user);
  const { password: _, ...userWithoutPassword } = user;
  return {
    user: userWithoutPassword,
    token
  };
};

// Register a new user with email and password
export const registerUser = async (name, email, password) => {
  // Simulate network delay
  await new Promise(resolve => setTimeout(resolve, 800));

  // Validate inputs
  if (!name || !email || !password) {
    throw new Error('All fields are required');
  }

  if (password.length < 6) {
    throw new Error('Password must be at least 6 characters');
  }

  // Check if user already exists
  if (users.some(u => u.email.toLowerCase() === email.toLowerCase())) {
    throw new Error('A user with this email already exists');
  }

  // Create new user
  const newUser = {
    id: Date.now().toString(),
    name: name.trim(),
    email: email.trim().toLowerCase(),
    password,
    createdAt: new Date().toISOString()
  };

  users.push(newUser);
  saveUsers();

  // Generate token and return user data (excluding password)
  const token = generateToken(newUser);
  const { password: _, ...userWithoutPassword } = newUser;
  return {
    user: userWithoutPassword,
    token
  };
};

